use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn js_string(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len() + 2);
    escaped.push('\'');
    for character in value.chars() {
        match character {
            '\\' => escaped.push_str("\\\\"),
            '\'' => escaped.push_str("\\'"),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            character if character.is_control() => {
                write!(escaped, "\\u{{{:x}}}", character as u32).unwrap();
            }
            character => escaped.push(character),
        }
    }
    escaped.push('\'');
    escaped
}

fn generate() -> String {
    let extensions: BTreeSet<_> = mime_guess::get_extensions("*", "*")
        .expect("mime_guess reverse mappings are enabled")
        .iter()
        .copied()
        .collect();

    let mut output = String::from(
        "// Generated from Rust's mime_guess by `npm run mime-data`.\n\
         // Do not edit this file directly.\n\n\
         export const MIME_TYPES_BY_EXTENSION = new Map([\n",
    );

    let mappings: Vec<_> = extensions
        .into_iter()
        .filter_map(|extension| {
            mime_guess::from_ext(extension)
                .first_raw()
                .map(|mime_type| (extension, mime_type))
        })
        .collect();

    for (index, (extension, mime_type)) in mappings.iter().enumerate() {
        writeln!(
            output,
            "  [{}, {}]{}",
            js_string(extension),
            js_string(mime_type),
            if index + 1 == mappings.len() { "" } else { "," }
        )
        .unwrap();
    }

    output.push_str("])\n");
    output
}

fn output_path(argument: Option<String>) -> Result<PathBuf, String> {
    argument
        .map(PathBuf::from)
        .ok_or_else(|| "usage: generate-mime-map [--check] <output-path>".to_string())
}

fn check(path: &Path, expected: &str) -> Result<(), String> {
    let current = fs::read_to_string(path)
        .map_err(|error| format!("could not read {}: {error}", path.display()))?;
    if current == expected {
        return Ok(());
    }

    Err(format!(
        "{} is stale; run `npm run mime-data` in frontend",
        path.display()
    ))
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|error| format!("could not create {}: {error}", parent.display()))?;
    }
    fs::write(path, contents)
        .map_err(|error| format!("could not write {}: {error}", path.display()))
}

fn run() -> Result<(), String> {
    let mut arguments = env::args().skip(1);
    let first = arguments.next();
    let (check_only, path) = if first.as_deref() == Some("--check") {
        (true, output_path(arguments.next())?)
    } else {
        (false, output_path(first)?)
    };
    if arguments.next().is_some() {
        return Err("usage: generate-mime-map [--check] <output-path>".to_string());
    }

    let generated = generate();
    if check_only {
        check(&path, &generated)
    } else {
        write(&path, &generated)
    }
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}
